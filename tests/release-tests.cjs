'use strict';
const fs=require('node:fs');const path=require('node:path');const assert=require('node:assert/strict');
const root=path.join(__dirname,'..');const read=p=>fs.readFileSync(path.join(root,p),'utf8');
let n=0;const ok=(x,m)=>{assert.ok(x,m);n++;};
const pkg=JSON.parse(read('package.json'));
// The footer is how users confirm an update installed, so it must track the version.
ok(read('index.html').includes(`<footer>v${pkg.version} `),`footer shows package version v${pkg.version}`);
ok(pkg.repository.url.includes('awkwardcarl/deadlockcounteradvisor.git'),'correct GitHub remote');
ok(pkg.build.publish.owner==='awkwardcarl'&&pkg.build.publish.repo==='deadlockcounteradvisor','pin update destination');
ok(pkg.build.publish.releaseType==='draft','review before publishing');
ok(pkg.build.win.target.includes('nsis'),'NSIS installer enables updates');
ok(pkg.dependencies['electron-updater'],'updater shipped as production dependency');
ok(pkg.build.win.signAndEditExecutable===false,'mitigate local signing utility issues');
ok(!Object.hasOwn(pkg.build.win,'signExecutable'),'reject unsupported electron-builder win.signExecutable key');
ok(pkg.build.nsis.deleteAppDataOnUninstall===false,'local preferences retained');
const workflow=read('.github/workflows/windows-release.yml');
ok(workflow.includes('workflow_dispatch'),'manual preview build');
ok(workflow.includes("tags:"),'tag gated releases');
ok(workflow.includes('GH_TOKEN: ${{ secrets.GITHUB_TOKEN }}'),'CI token only');
ok(workflow.includes('version v$version'),'release tag matches package version');
ok(workflow.includes('npm run build:win:installer')&&workflow.includes('npm run release:win'),'separate preview and publish builds');
ok(workflow.includes('npm test'),'CI tests');
const lock=JSON.parse(read('package-lock.json'));
const locked=name=>lock.packages?.['node_modules/'+name]?.version;
ok(Object.entries({...pkg.dependencies,...pkg.devDependencies}).every(([name,version])=>locked(name)===version),'package-lock.json matches package.json');
ok(workflow.includes('npm ci')&&!workflow.includes('npm install'),'CI installs exactly the locked dependencies');
const main=read('desktop/main.cjs'), preload=read('desktop/preload.cjs'), js=read('js/ui.js'), html=read('index.html');
ok(main.includes('requestSingleInstanceLock()')&&main.includes("'second-instance'"),'second launch focuses the running window');
ok(main.includes("'app-update.yml'"),'updater gated on installer metadata');
ok(main.includes('setTimeout(()=>void updates.check(),8000)'),'startup check only');
ok(preload.includes('updates:download')&&preload.includes('updates:install'),'narrow update IPC');
ok(!main.includes('ReadProcessMemory')&&!js.includes('new WebSocket('),'no prohibited game telemetry');
ok(main.includes('if(!trusted(event))'),'IPC caller verification');
ok(html.includes('id="updateAction"')&&html.includes('id="updateStatus"'),'update controls rendered');
ok(js.includes('Install & restart')&&js.includes('window.confirm('),'user restart confirmation');
ok(read('desktop/updater.cjs').includes('autoDownload=false')&&read('desktop/updater.cjs').includes('autoInstallOnAppQuit=false'),'no forced update behavior');
ok(read('desktop/security.cjs').includes('permittedImageURL'),'strict renderer network restrictions retained');
// All rights reserved: the source is public for transparency, not open source.
const license=read('LICENSE');
ok(/^Copyright \(c\) 2026 .+\. All rights reserved\./.test(license)&&license.includes('It is not open')&&license.includes('No license is granted to use, copy, modify'),'LICENSE reserves all rights');
ok(license.includes('SIL\n  Open Font License 1.1')||/SIL\s+Open Font License 1\.1/.test(license),'LICENSE leaves the bundled fonts under their own license');
ok(pkg.private===true&&pkg.license==='UNLICENSED'&&JSON.parse(read('package-lock.json')).packages[''].license==='UNLICENSED','package marked proprietary (never published to npm)');
ok(read('README.md').includes('All rights reserved')&&read('README.md').includes('[LICENSE](LICENSE)'),'README states the license');
console.log(`PASS: ${n} repository, release, updater, and privacy checks`);
